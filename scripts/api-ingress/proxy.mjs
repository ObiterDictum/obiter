export function sha256(buffer) {
  return createHash('sha256').update(buffer).digest('hex')
}

export function freePort() {
  return new Promise((resolvePort, reject) => {
    const probe = createServer()
    probe.on('error', reject)
    probe.listen(0, '127.0.0.1', () => {
      const address = probe.address()
      probe.close(() => resolvePort(address.port))
    })
  })
}

export function syntheticText(targetBytes) {
  const line =
    'Ingress boundary check: synthetic legal correspondence, no client data. ' +
    'Boundary fence title plan covenant easement conveyance counterpart.\n'
  const buffer = Buffer.from(line.repeat(Math.ceil(targetBytes / line.length)))
  return buffer.subarray(0, targetBytes)
}


export function apiRequest({
  port,
  path,
  method = 'GET',
  token,
  body,
  headers = {},
  timeoutMs = 30_000,
}) {
  return new Promise((resolveRequest) => {
    const request = httpRequest(
      {
        host: '127.0.0.1',
        port,
        path,
        method,
        headers: {
          Host: API_HOST,
          ...(token ? bearer(token) : {}),
          ...headers,
        },
      },
      (response) => {
        const chunks = []
        response.on('data', (chunk) => chunks.push(chunk))
        response.on('end', () =>
          resolveRequest({
            status: response.statusCode,
            headers: response.headers,
            body: Buffer.concat(chunks),
          }),
        )
      },
    )
    request.setTimeout(timeoutMs, () => request.destroy(new Error('timeout')))
    request.on('error', (error) =>
      resolveRequest({
        status: 0,
        headers: {},
        body: Buffer.alloc(0),
        error: error.message,
      }),
    )
    if (body) request.write(body)
    request.end()
  })
}

export async function healthThroughProxy(port) {
  const response = await apiRequest({ port, path: '/api/health' })
  let parsed = null
  try {
    parsed = JSON.parse(response.body.toString('utf8'))
  } catch {
    parsed = null
  }
  return { status: response.status, runtime: parsed?.runtime ?? null, parsed }
}

export function waitForRuntime(port, runtime, timeoutMs = 60_000) {
  return waitFor(
    async () => {
      const health = await healthThroughProxy(port)
      return health.status === 200 && health.runtime === runtime ? health : null
    },
    { timeoutMs, label: `api runtime=${runtime} through Traefik` },
  )
}

export function readSlowly({ port, path, token, pauseMs = 40 }) {
  return new Promise((resolveRead) => {
    const started = Date.now()
    let bytes = 0
    let chunks = 0
    let status = 0
    const hash = createHash('sha256')
    const request = httpRequest(
      {
        host: '127.0.0.1',
        port,
        path,
        headers: { Host: API_HOST, ...(token ? bearer(token) : {}) },
      },
      (response) => {
        status = response.statusCode
        response.on('data', (chunk) => {
          bytes += chunk.length
          chunks += 1
          hash.update(chunk)
          response.pause()
          setTimeout(() => response.resume(), pauseMs)
        })
        response.on('end', () =>
          resolveRead({
            status,
            bytes,
            chunks,
            sha256: hash.digest('hex'),
            elapsedMs: Date.now() - started,
            complete: true,
          }),
        )
        response.on('error', (error) =>
          resolveRead({
            status,
            bytes,
            chunks,
            sha256: hash.digest('hex'),
            elapsedMs: Date.now() - started,
            complete: false,
            error: error.message,
          }),
        )
      },
    )
    request.on('error', (error) =>
      resolveRead({
        status,
        bytes,
        chunks,
        sha256: hash.digest('hex'),
        elapsedMs: Date.now() - started,
        complete: false,
        error: error.message,
      }),
    )
    request.end()
  })
}

export function pacedUpload({
  port,
  host,
  path,
  totalBytes,
  body,
  headers = {},
  intervalMs = PACED_INTERVAL_MS,
  onProgress,
}) {
  return new Promise((resolveUpload) => {
    const started = Date.now()
    let sent = 0
    let status = 0
    let responseBody = ''
    const filler = Buffer.alloc(PACED_CHUNK_BYTES, 0x62)
    const request = httpRequest(
      {
        host: '127.0.0.1',
        port,
        path,
        method: 'POST',
        headers: {
          Host: host,
          'Content-Type': 'application/octet-stream',
          'Content-Length': String(totalBytes),
          ...headers,
        },
      },
      (response) => {
        status = response.statusCode
        response.on('data', (part) => {
          responseBody += part
        })
        response.on('end', () =>
          resolveUpload({
            status,
            responseBody,
            sent,
            elapsedMs: Date.now() - started,
            complete: true,
          }),
        )
      },
    )
    request.on('error', (error) =>
      resolveUpload({
        status,
        responseBody,
        sent,
        elapsedMs: Date.now() - started,
        complete: false,
        error: error.message,
      }),
    )
    const tick = () => {
      if (sent >= totalBytes) {
        request.end()
        return
      }
      const remaining = totalBytes - sent
      const size = Math.min(PACED_CHUNK_BYTES, remaining)
      const slice = body
        ? body.subarray(sent, sent + size)
        : filler.subarray(0, size)
      const writable = request.write(slice)
      sent += size
      onProgress?.({ sent, total: totalBytes, elapsedMs: Date.now() - started })
      if (writable) setTimeout(tick, intervalMs)
      else request.once('drain', () => setTimeout(tick, intervalMs))
    }
    tick()
  })
}


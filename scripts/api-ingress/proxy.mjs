export function headerProbe({ port, host, headerBytes, path = '/headers' }) {
  return new Promise((resolveProbe) => {
    const request = httpRequest(
      {
        host: '127.0.0.1',
        port,
        path,
        headers: { Host: host, 'X-Probe': 'a'.repeat(headerBytes) },
      },
      (response) => {
        const chunks = []
        response.on('data', (chunk) => chunks.push(chunk))
        response.on('end', () =>
          resolveProbe({
            status: response.statusCode,
            body: Buffer.concat(chunks).toString('utf8'),
          }),
        )
      },
    )
    request.setTimeout(20_000, () => request.destroy(new Error('timeout')))
    request.on('error', (error) =>
      resolveProbe({ status: 0, error: error.message }),
    )
    request.end()
  })
}
